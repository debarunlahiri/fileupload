CREATE SEQUENCE IF NOT EXISTS SEQ_FILE_MNG START WITH 1;
CREATE SEQUENCE IF NOT EXISTS SEQ_FILE_REG START WITH 1;

-- one row per uploaded file; files sharing FILE_MNG_NO belong to one control
CREATE TABLE IF NOT EXISTS ATTACH_FILE (
  FILE_REG_NO  VARCHAR(20)  NOT NULL PRIMARY KEY,
  FILE_MNG_NO  VARCHAR(20)  NOT NULL,
  BASE_PATH    VARCHAR(500) NOT NULL,
  DETAIL_PATH  VARCHAR(200) NOT NULL,
  PHIS_FILE_NM VARCHAR(100) NOT NULL,
  LOGI_FILE_NM VARCHAR(255) NOT NULL,
  FILE_EXT     VARCHAR(20),
  FILE_SIZE    BIGINT       NOT NULL,
  PGM_ID       VARCHAR(50),
  PATH_KEY     VARCHAR(50),
  REG_DT       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_ATTACH_FILE_MNG ON ATTACH_FILE (FILE_MNG_NO);

-- older databases: add the column that tells the upload boxes apart
ALTER TABLE ATTACH_FILE ADD COLUMN IF NOT EXISTS PATH_KEY VARCHAR(50);

-- sample business record (page SAF0101): ONE file manager no shared by both upload boxes
CREATE TABLE IF NOT EXISTS SAF_RECORD (
  ID              BIGINT AUTO_INCREMENT PRIMARY KEY,
  TITLE           VARCHAR(200),
  FILE_MNG_NO     VARCHAR(20)
);
ALTER TABLE SAF_RECORD ADD COLUMN IF NOT EXISTS FILE_MNG_NO VARCHAR(20);
